import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('tokens per page resizes preview and downloads 12 tokens on each full A4 page', async ({ page }, testInfo) => {
  test.setTimeout(120000)
  page.on('pageerror', error => console.error('Browser error:', error.message))
  page.on('console', message => { if (message.type() === 'error') console.error(message.text()) })
  await page.addInitScript(() => {
    const account = { id: 1, accountType: 'SOCIETY', accountName: 'Pramukh Glory Society', role: 'ADMIN' }
    localStorage.setItem('token', 'test-token')
    localStorage.setItem('user', JSON.stringify({ id: 1, name: 'Test User' }))
    localStorage.setItem('currentAccount', JSON.stringify(account))
    localStorage.setItem('accounts', JSON.stringify([account]))
    localStorage.setItem('lastActivityAt', String(Date.now()))
  })
  await page.route(url => url.pathname.startsWith('/api/'), route => route.fulfill({ json: {} }))
  await page.goto('/society/festival-tokens')
  await expect(page.getByLabel('Token design')).toHaveValue('ornate')
  await expect.poll(() => page.locator('.festival-token-cell canvas').first().evaluate(canvas => canvas.width)).toBe(720)
  await page.getByLabel('Token design').selectOption('custom')
  await expect(page.getByText('200 tokens · 13 A4 pages')).toBeVisible()
  await expect(page.getByRole('img', { name: 'token 1', exact: true })).toBeVisible()
  await expect(page.getByLabel('Last kids token')).toHaveCount(0)
  await page.getByLabel('Show Adults / Kids on tokens').check()
  await expect(page.getByRole('img', { name: 'Kids token 1', exact: true })).toBeVisible()
  await expect(page.locator('.festival-token-cell')).toHaveCount(16)
  for (const count of [4, 8, 20, 12]) {
    await page.getByLabel('Tokens per A4 page').selectOption(String(count))
    await expect(page.locator('.festival-token-cell')).toHaveCount(count)
    const fits = await page.locator('.festival-token-sheet').evaluate(sheet => {
      const outer = sheet.getBoundingClientRect()
      return [...sheet.querySelectorAll('canvas')].every(canvas => {
        const rect = canvas.getBoundingClientRect()
        const cell = canvas.parentElement.getBoundingClientRect()
        return rect.top >= cell.top && rect.bottom <= cell.bottom && rect.left >= cell.left && rect.right <= cell.right && cell.bottom <= outer.bottom
      })
    })
    expect(fits).toBe(true)
  }
  await expect(page.getByText('200 tokens · 17 A4 pages')).toBeVisible()
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Kids token 50', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Adults token 51', exact: true })).toBeVisible()
  const background = () => page.locator('.festival-token-cell canvas').first().evaluate(canvas => [...canvas.getContext('2d').getImageData(240, 110, 1, 1).data])
  await expect.poll(async () => (await background())[0]).toBeGreaterThan(200)
  await page.getByLabel('Dark token background').check()
  await expect.poll(async () => (await background())[0]).toBeLessThan(80)
  await expect(page.getByLabel('Dark design')).toHaveValue('midnight')
  const midnightBackground = await background()
  await page.getByLabel('Dark design').selectOption('classic')
  await expect.poll(background).not.toEqual(midnightBackground)
  await page.getByLabel('Dark design').selectOption('midnight')
  await expect.poll(background).toEqual(midnightBackground)
  const dancerControl = page.getByLabel('Show dancer artwork')
  await expect(dancerControl).toBeChecked()
  await dancerControl.uncheck()
  const artworkPixels = () => page.locator('.festival-token-cell canvas').first().evaluate(canvas => canvas.toDataURL())
  const withoutDancers = await artworkPixels()
  await dancerControl.check()
  await expect.poll(artworkPixels).not.toEqual(withoutDancers)
  await dancerControl.uncheck()
  await expect.poll(artworkPixels).toEqual(withoutDancers)
  await dancerControl.check()
  await expect.poll(artworkPixels).not.toEqual(withoutDancers)
  await page.getByLabel('Ribbon label').fill('ENTRY')
  await expect(page.getByLabel('Ribbon label')).toHaveValue('ENTRY')
  await page.getByLabel('Dark token background').uncheck()
  await expect.poll(async () => (await background())[0]).toBeGreaterThan(200)
  await page.getByLabel('Dark token background').check()
  await expect.poll(async () => (await background())[0]).toBeLessThan(80)
  await page.screenshot({ path: testInfo.outputPath('kids-adults-preview.png'), fullPage: true })
  await page.getByLabel('Token design').selectOption('ornate')
  await page.getByLabel('Festival / event').fill('Navratri Mahotsav')
  await expect.poll(() => page.locator('.festival-token-cell canvas').first().evaluate(canvas => canvas.width)).toBe(720)
  const alphaAt = (x, y) => page.locator('.festival-token-cell canvas').first().evaluate((canvas, point) => canvas.getContext('2d').getImageData(point.x, point.y, 1, 1).data[3], { x, y })
  await expect.poll(() => alphaAt(0, 0)).toBe(0)
  await expect.poll(() => alphaAt(719, 719)).toBe(0)
  await expect.poll(() => alphaAt(360, 360)).toBe(255)
  await page.screenshot({ path: testInfo.outputPath('ornate-preview.png'), fullPage: true })
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download A4 PDF' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('festival-tokens-1-200.pdf')
  const path = testInfo.outputPath('tokens.pdf')
  await download.saveAs(path)
  const pdf = (await readFile(path)).toString('latin1')
  expect(pdf.startsWith('%PDF-')).toBe(true)
  expect(pdf.match(/\/Type \/Page\b/g)).toHaveLength(17)
  expect(pdf.match(/\/MediaBox \[0 0 595\.28 841\.89\]/g)).toHaveLength(17)
  // PNG alpha masks create a second image object for each numbered badge.
  expect(pdf.match(/\/Subtype \/Image\b/g)).toHaveLength(400)
  await page.getByLabel('Last token', { exact: true }).fill('40')
  await expect(page.locator('.festival-token-error')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Download A4 PDF' })).toBeDisabled()
  await page.getByLabel('Show Adults / Kids on tokens').uncheck()
  await expect(page.locator('.festival-token-error')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Download A4 PDF' })).toBeEnabled()
})
